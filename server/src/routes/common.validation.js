const { body, param, query } = require("express-validator");
const { MAX_AMOUNT } = require("../utils/money");
const { MAX_LIMIT } = require("../utils/pagination");

const MAX_ID = Number.MAX_SAFE_INTEGER;

const idParam = (name, label) =>
  param(name)
    .isInt({ min: 1, max: MAX_ID, allow_leading_zeroes: false })
    .withMessage(`Invalid ${label}: must be a positive integer`)
    .toInt();

const idBody = (name) =>
  body(name)
    .exists({ values: "null" })
    .withMessage(`${name} is required`)
    .bail()
    .isInt({ min: 1, max: MAX_ID, allow_leading_zeroes: false })
    .withMessage(`Invalid ${name}: must be a positive integer`)
    .toInt();

const amountBody = (name = "amount") =>
  body(name)
    .exists({ values: "null" })
    .withMessage(`${name} is required`)
    .bail()
    .custom((value) => {
      const isScalar = typeof value === "number" || (typeof value === "string" && value.trim() !== "");
      const numeric = Number(value);
      if (!isScalar || !Number.isFinite(numeric)) throw new Error(`${name} must be a valid number`);
      if (numeric <= 0) throw new Error(`${name} must be greater than 0`);
      if (numeric > MAX_AMOUNT) throw new Error(`${name} must not exceed ${MAX_AMOUNT}`);
      if (!/^\d+(\.\d{1,2})?$/.test(String(value).trim())) {
        throw new Error(`${name} can have at most 2 decimal places`);
      }
      return true;
    });

const referenceIdBody = ({ reservedPrefix } = {}) => {
  let chain = body("reference_id")
    .exists({ values: "null" })
    .withMessage("reference_id is required")
    .bail()
    .isString()
    .withMessage("reference_id must be a string")
    .bail()
    .trim()
    .notEmpty()
    .withMessage("reference_id is required")
    .bail()
    .isLength({ max: 100 })
    .withMessage("reference_id must be at most 100 characters");

  if (reservedPrefix) {
    chain = chain
      .bail()
      .custom((value) => !value.toUpperCase().startsWith(reservedPrefix))
      .withMessage(`reference_id must not start with "${reservedPrefix}" (reserved for transfers)`);
  }
  return chain;
};

const descriptionBody = () =>
  body("description")
    .optional({ values: "null" })
    .isString()
    .withMessage("description must be a string")
    .bail()
    .trim()
    .isLength({ max: 255 })
    .withMessage("description must be at most 255 characters");

/** Fields that are always system-generated and must never come from the client. */
const forbiddenBody = (fields) =>
  fields.map((field) =>
    body(field)
      .not()
      .exists()
      .withMessage(`${field} is generated by the system and cannot be set by the client`),
  );

const paginationQuery = () => [
  query("page").optional().isInt({ min: 1, max: MAX_ID }).withMessage("page must be a positive integer").toInt(),
  query("limit")
    .optional()
    .isInt({ min: 1, max: MAX_LIMIT })
    .withMessage(`limit must be an integer between 1 and ${MAX_LIMIT}`)
    .toInt(),
];

const typeQuery = () =>
  query("type")
    .optional({ values: "falsy" })
    .trim()
    .toLowerCase()
    .isIn(["credit", "debit"])
    .withMessage('type must be either "credit" or "debit"');

const searchQuery = () =>
  query("search").optional().isString().trim().isLength({ max: 100 }).withMessage("search must be at most 100 characters");

module.exports = {
  idParam,
  idBody,
  amountBody,
  referenceIdBody,
  descriptionBody,
  forbiddenBody,
  paginationQuery,
  typeQuery,
  searchQuery,
};
